"""Summarize recorded LLM failures for one run from the ledger (offline).

Every number in ``docs/reports/P1-gemini-pilot-diagnosis.md`` comes from this
script: the ledger's per-attempt root cause columns and the run's
``failures.jsonl``. No API call is made and no key is read or printed.
"""

from __future__ import annotations

import argparse
import json
import re
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path

from axion.config.settings import Settings
from axion.llm.ledger import CallRecord, SQLiteLedger
from axion.llm.pacing import PACIFIC, next_midnight_pacific, requests_by_pacific_day


def _fmt(value: object) -> str:
    return "—" if value is None else str(value)


def _display_fields(row: CallRecord) -> tuple[str | None, int | None, str | None]:
    """Root-cause columns, falling back to parsing pre-migration error text.

    Ledger rows written before the structured columns existed only carry the
    error string. Parsing it keeps the historical diagnosis honest instead of
    labelling every old attempt "unclassified".
    """
    error_class = row.error_class
    http_status = row.http_status
    provider_status = row.error_status
    if not row.error:
        return error_class, http_status, provider_status
    text = row.error
    if error_class is None:
        match = re.match(r"([A-Za-z]+Error):", text)
        if match:
            error_class = match.group(1)
    if http_status is None:
        match = re.search(r"\((\d{3})(?:/|\b)", text)
        if match:
            http_status = int(match.group(1))
    if provider_status is None:
        match = re.search(r'\\?"status\\?"\s*:\s*\\?"([A-Z_]+)\\?"', text)
        if match:
            provider_status = match.group(1)
    return error_class, http_status, provider_status


def _markdown(
    *,
    run_id: str,
    rows: list[CallRecord],
    failures: list[dict[str, object]],
    by_day: dict[str, int],
    model: str,
) -> str:
    successes = [row for row in rows if row.error is None]
    errors = [row for row in rows if row.error is not None]
    display = {row.id: _display_fields(row) for row in rows}
    classes = Counter(str(display[row.id][0] or "unclassified") for row in errors)
    today = datetime.now(UTC).astimezone(PACIFIC).date().isoformat()
    lines = [
        "# P1-10 Gemini pilot failure diagnosis",
        "",
        f"Generated by `python scripts/failure_report.py --run-id {run_id}`.",
        f"Run: `{run_id}`; model: `{model}`.",
        "",
        "## Recorded attempts",
        "",
        f"- Attempts recorded: **{len(rows)}**; succeeded: **{len(successes)}**; "
        f"failed: **{len(errors)}**",
        "- Root causes: "
        + ", ".join(f"`{name}` ({count})" for name, count in sorted(classes.items())),
        f"- Requests by Pacific day: {by_day}; today (`{today}`) used **{by_day.get(today, 0)}**",
        "",
        "| Ledger id | Timestamp (UTC) | Root cause | HTTP | Provider status | Finish | "
        "Latency ms | Prompt tok | Completion tok | Thinking tok |",
        "| --: | :-- | :-- | --: | :-- | :-- | --: | --: | --: | --: |",
    ]
    for row in rows:
        error_class, http_status, provider_status = display[row.id]
        lines.append(
            f"| {row.id} | {row.ts} | `{_fmt(error_class)}` | {_fmt(http_status)} | "
            f"{_fmt(provider_status)} | {_fmt(row.finish_reason)} | "
            f"{_fmt(None if row.latency_ms is None else round(row.latency_ms))} | "
            f"{_fmt(row.prompt_tokens or None)} | {_fmt(row.completion_tokens or None)} | "
            f"{_fmt(row.reasoning_tokens or None)} |"
        )
    lines += [
        "",
        "## Run failure records",
        "",
        "| Paper | Reason | Error class | Provider status | HTTP | Attempts | Message |",
        "| :-- | :-- | :-- | :-- | --: | --: | :-- |",
    ]
    for failure in failures:
        lines.append(
            f"| `{_fmt(failure.get('paper_id'))}` | `{_fmt(failure.get('reason'))}` | "
            f"`{_fmt(failure.get('error_class'))}` | {_fmt(failure.get('provider_status'))} | "
            f"{_fmt(failure.get('http_status'))} | {_fmt(failure.get('attempts'))} | "
            f"{_fmt(failure.get('error_message'))} |"
        )
    lines += [
        "",
        "## Quota",
        "",
        "- Next Pacific reset: "
        f"`{next_midnight_pacific(datetime.now(UTC).astimezone(PACIFIC).date())}`",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-id", default="p1-10-gemini-pilot-s20261114-n5")
    parser.add_argument("--model", default="gemini-3.8-flash")
    parser.add_argument("--failures", type=Path, default=None)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("docs/reports/P1-gemini-pilot-diagnosis.md"),
    )
    args = parser.parse_args(argv)

    ledger = SQLiteLedger(Settings().resolved_ledger_path)
    rows = list(ledger.calls_for_run(args.run_id))
    if not rows:
        print(f"no ledger rows for run {args.run_id!r}", flush=True)
        return 1
    failures: list[dict[str, object]] = []
    if args.failures is not None and args.failures.exists():
        for line in args.failures.read_text(encoding="utf-8").splitlines():
            if line.strip():
                failures.append(json.loads(line))

    markdown = _markdown(
        run_id=args.run_id,
        rows=list(rows),
        failures=failures,
        by_day=requests_by_pacific_day(rows),
        model=args.model,
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(markdown + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {args.out} ({len(rows)} attempts, {len(failures)} failure records)", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
