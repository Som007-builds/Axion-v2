"""P2-03a sample plan: gold exclusion, existing labels, and nested increments.

Counts only. No LLM call, no label, no corpus mutation. Every number the TODO
quotes for the sample ceiling comes from this script.

Usage:
    python scripts/teacher_sample_plan.py
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

from axion.eval.cost_estimate import DEFAULT_SEED, sample_papers_excluding
from axion.ingest.corpus import read_manifest, read_papers_csv

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MANIFEST = ROOT / "docs" / "reports" / "P1-corpus-manifest.json"
DEFAULT_AUDIT = ROOT / "eval" / "audit" / "claims_audit_v1.csv"
DEFAULT_BASELINE = ROOT / "eval" / "silver" / "claims_v1" / "baseline_flashlite"
DEFAULT_REPORT = ROOT / "docs" / "reports" / "P2-03a-sample.md"
INCREMENTS = (50, 100, 200, 300)
CEILING = 300


def _gold_ids(path: Path) -> set[str]:
    rows = csv.DictReader(path.read_text(encoding="utf-8").splitlines())
    return {row["paper_id"].strip() for row in rows if row.get("paper_id")}


def _processed_ids(path: Path) -> set[str]:
    if not path.exists():
        return set()
    ids: set[str] = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            ids.add(str(json.loads(line)["paper_id"]))
    return ids


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--audit", type=Path, default=DEFAULT_AUDIT)
    parser.add_argument("--baseline-dir", type=Path, default=DEFAULT_BASELINE)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    args = parser.parse_args(argv)

    manifest = read_manifest(args.manifest)
    papers = read_papers_csv(args.manifest.parent / Path(manifest.files.papers_csv).name)
    gold = _gold_ids(args.audit)
    labelled = _processed_ids(args.baseline_dir / "papers_processed.jsonl")
    labelled_non_gold = labelled - gold
    claims = 0
    claims_path = args.baseline_dir / "silver_claims.jsonl"
    if claims_path.exists():
        claims = sum(
            1
            for line in claims_path.read_text(encoding="utf-8").splitlines()
            if line.strip() and json.loads(line)["paper_id"] not in gold
        )

    excluded = frozenset(gold | labelled)
    corpus_ids = {paper.pmcid for paper in papers}
    missing_gold = sorted(gold - corpus_ids)

    rows = [
        "# P2-03a teacher sample plan",
        "",
        "> Generated by `python scripts/teacher_sample_plan.py`. Counts only: no LLM call,",
        "> no label created, no corpus change.",
        "",
        "## Inputs",
        "",
        f"- Corpus papers: **{len(papers):,}**",
        f"- Gold audit papers (excluded from all teacher labelling): **{len(gold)}**",
        "- Non-gold papers already teacher-labelled by the P1 baseline: "
        f"**{len(labelled_non_gold)}** ({claims:,} silver claims)",
        f"- Papers already used by the baseline in total (gold + non-gold): **{len(labelled)}**",
        f"- Seeded draw order: seed **{args.seed}**, one permutation of the eligible papers;",
        "  every increment is a prefix of it, so no paper is ever labelled twice.",
        "",
        "## Increments",
        "",
        "| Target (non-gold labelled total) | New papers | Requests at 1/paper "
        "| Requests at 1.6x overhead |",
        "| --: | --: | --: | --: |",
    ]
    for target in INCREMENTS:
        new = max(0, target - len(labelled_non_gold))
        rows.append(f"| {target} | {new} | {new} | {int(new * 1.6)} |")

    sample = sample_papers_excluding(papers, 45, seed=args.seed, exclude=excluded)
    gold_in_draw = sum(1 for paper in sample if paper.pmcid in gold)
    labelled_in_draw = sum(1 for paper in sample if paper.pmcid in labelled)
    rows.extend(
        [
            "",
            "## First increment (to 100 non-gold labelled papers)",
            "",
            f"- New papers: **{len(sample)}** (45), bringing the non-gold total to 100.",
            f"- Drawn from **{len(papers) - len(excluded):,}** eligible papers.",
            f"- Gold papers in the draw: **{gold_in_draw}** (must be 0).",
            f"- Already-labelled papers in the draw: **{labelled_in_draw}** (must be 0).",
            f"- Daily cap: 450 requests; ceiling is {CEILING} labelled papers.",
            "",
            "## Limits",
            "",
            "- Request counts are paper counts times an observed overhead; retries consume quota",
            "  and the 503 rate varies by hour (see `docs/reports/P2-provider-reliability.md`).",
            "- This plan sizes the sample. It does not claim a learning-curve effect; that is",
            "  P2-03c and it may stop the labelling early.",
        ]
    )
    if missing_gold:
        rows.extend(
            [
                "",
                f"**WARNING:** {len(missing_gold)} gold paper IDs are not in the corpus manifest: "
                f"{', '.join(missing_gold[:10])}",
            ]
        )

    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text("\n".join(rows) + "\n", encoding="utf-8", newline="\n")
    print(
        f"corpus={len(papers)} gold={len(gold)} labelled_non_gold={len(labelled_non_gold)} "
        f"claims={claims} excluded={len(excluded)} draw={len(sample)} "
        f"gold_in_draw={gold_in_draw}"
    )
    print(f"report: {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
