"""Gold audit by section, plus a seeded skim list of non-core claims.

No labels are created here: every number comes from `eval/audit/claims_audit_v1.csv`.
The claim list is for the owner to read and characterise; this script does not
decide whether a claim is a finding or background prose.

Usage:
    python scripts/gold_by_section.py
"""

from __future__ import annotations

import argparse
import csv
import random
from pathlib import Path

from axion.eval.audit import wilson_interval
from axion.extract.sections import load_section_sets

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_AUDIT = ROOT / "eval" / "audit" / "claims_audit_v1.csv"
DEFAULT_REPORT = ROOT / "docs" / "reports" / "P2-gold-by-section.md"
DEFAULT_SEED = 20261116
SKIM_COUNT = 15


def _is_core(section: str, patterns: tuple[str, ...]) -> bool:
    haystack = section.casefold()
    return any(pattern.casefold() in haystack for pattern in patterns)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--audit", type=Path, default=DEFAULT_AUDIT)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--skim", type=int, default=SKIM_COUNT)
    args = parser.parse_args(argv)

    rows = list(csv.DictReader(args.audit.read_text(encoding="utf-8").splitlines()))
    labelled = [row for row in rows if row["label"].strip()]
    if not labelled:
        print("no labelled rows in the audit")
        return 1

    core_patterns = load_section_sets().require("core").include

    def _pct(value: float) -> str:
        return f"{value * 100:.1f}%"

    by_section: dict[str, list[str]] = {}
    for row in labelled:
        by_section.setdefault(row["section"].strip(), []).append(row["label"].strip())

    total = len(labelled)
    correct = sum(1 for row in labelled if row["label"].strip() == "CORRECT")
    core_rows = [row for row in labelled if _is_core(row["section"], core_patterns)]
    core_correct = sum(1 for row in core_rows if row["label"].strip() == "CORRECT")

    lines = [
        "# Gold audit by section",
        "",
        "> Generated by `python scripts/gold_by_section.py` from",
        "> `eval/audit/claims_audit_v1.csv`. **No labels were created or changed here.**",
        "> `core` = sections matching the `core` set in `src/axion/config/section_sets.yaml`",
        "> (abstract / results / conclusion); everything else is `non-core`.",
        "",
        "## Overall",
        "",
        f"- Labelled claims: **{total}**; CORRECT: **{correct}** ({_pct(correct / total)})",
        f"- Core-section claims: **{len(core_rows)}** ({_pct(len(core_rows) / total)}), "
        f"CORRECT {core_correct} ({_pct(core_correct / len(core_rows)) if core_rows else 'n/a'})",
        f"- Non-core claims: **{total - len(core_rows)}** "
        f"({_pct(1 - len(core_rows) / total)}), "
        f"CORRECT {correct - core_correct} "
        f"({_pct((correct - core_correct) / (total - len(core_rows)))})",
        "",
        "## By section",
        "",
        "Sections are the labels recorded by the P1 baseline. Small cells are unstable;",
        "read `n` before reading the rate.",
        "",
        "| Section | n | CORRECT | Precision | Wilson 95% CI |",
        "| :-- | --: | --: | --: | :-- |",
    ]
    for section in sorted(by_section, key=lambda name: (-len(by_section[name]), name.casefold())):
        labels = by_section[section]
        ok = sum(1 for label in labels if label == "CORRECT")
        low, high = wilson_interval(ok, len(labels))
        lines.append(
            f"| {section} | {len(labels)} | {ok} | {_pct(ok / len(labels))} | "
            f"{_pct(low)} to {_pct(high)} |"
        )

    non_core = [row for row in labelled if not _is_core(row["section"], core_patterns)]
    pick = random.Random(args.seed).sample(non_core, min(args.skim, len(non_core)))
    pick.sort(key=lambda row: (row["paper_id"], row["claim_id"]))
    lines.extend(
        [
            "",
            "## Skim list: random non-core gold claims",
            "",
            f"Seeded draw (seed {args.seed}) of **{len(pick)}** of the "
            f"{len(non_core)} non-core claims,",
            "for the owner to characterise. These are **not** classified here; the list states",
            "only what the audit row records.",
            "",
        ]
    )
    for index, row in enumerate(pick, start=1):
        label = row["label"].strip()
        lines.extend(
            [
                f"**{index}. `{row['paper_id']}` — {row['section']} — gold label `{label}`**",
                "",
                f"> {row['claim_text'].strip()}",
                "",
            ]
        )

    lines.extend(
        [
            "## Limits",
            "",
            "- Precision only: the audit samples the P1 baseline's own output, so absolute recall",
            "  is unmeasured and section-level cells are small.",
            "- Sections are the baseline's recorded labels; near-duplicate headings appear",
            "  separately (for example numbered and unnumbered results sections).",
            "",
        ]
    )
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"labelled={total} correct={correct} core={len(core_rows)} non_core={len(non_core)}")
    print(f"report: {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
