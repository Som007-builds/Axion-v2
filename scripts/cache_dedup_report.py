"""P2-04 cache and dedup census.

Reads the ledger read-only, then measures sentence repetition across the frozen
100-paper baseline sample. It makes no LLM call and changes no prompt.

Usage:
    python scripts/cache_dedup_report.py [--report docs/reports/P2-04-cache-dedup.md]
"""

from __future__ import annotations

import argparse
import json
import sqlite3
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path

from axion.extract.claims import build_baseline_document
from axion.extract.dedup import (
    NEAR_DUPLICATE_THRESHOLD,
    DedupStats,
    DuplicateGroup,
    dedup_stats,
)
from axion.parse.jats import parse_jats_file, split_sentences

ROOT = Path(__file__).resolve().parents[1]
LEDGER = ROOT / "data/ledger.sqlite3"
SOURCE = ROOT / "data/raw/europepmc/fulltext"
BASELINE_RUN = ROOT / "eval/silver/claims_v1/baseline_flashlite"
PROBE_RUN = "p2-04-cache-probe"
DEFAULT_REPORT = ROOT / "docs/reports/P2-04-cache-dedup.md"
MIN_CHARS = 20


def ledger_rows() -> list[sqlite3.Row]:
    if not LEDGER.exists():
        raise SystemExit(f"missing ledger: {LEDGER}")
    connection = sqlite3.connect(LEDGER)
    connection.row_factory = sqlite3.Row
    try:
        return connection.execute(
            """
            SELECT run_id, COUNT(*) AS calls,
                   SUM(CASE WHEN cache_hit = 1 THEN 1 ELSE 0 END) AS cache_hits,
                   SUM(usd) AS usd,
                   SUM(CASE WHEN cache_hit = 1 THEN prompt_tokens ELSE 0 END)
                       AS cache_prompt_tokens,
                   SUM(CASE WHEN cache_hit = 1 AND usd != 0 THEN 1 ELSE 0 END) AS priced_hits
            FROM llm_calls
            GROUP BY run_id
            ORDER BY run_id
            """
        ).fetchall()
    finally:
        connection.close()


def cache_size() -> int:
    connection = sqlite3.connect(LEDGER)
    try:
        row = connection.execute("SELECT COUNT(*) FROM llm_cache").fetchone()
    finally:
        connection.close()
    return int(row[0]) if row else 0


def baseline_papers() -> list[str]:
    path = BASELINE_RUN / "papers_processed.jsonl"
    return sorted(
        {
            str(row["paper_id"])
            for line in path.read_text(encoding="utf-8").splitlines()
            if line.strip() and (row := json.loads(line)).get("paper_id")
        }
    )


def census(
    paper_ids: list[str], threshold: float
) -> tuple[DedupStats, list[DuplicateGroup], Counter[str]]:
    texts: list[str] = []
    owners: list[str] = []
    per_paper: Counter[str] = Counter()
    for paper_id in paper_ids:
        path = SOURCE / f"{paper_id}.xml"
        if not path.exists():
            continue
        document = build_baseline_document(parse_jats_file(path, paper_id=paper_id))
        for section in document.sections:
            for sentence in split_sentences(section.text):
                sentence = sentence.strip()
                if len(sentence) < MIN_CHARS:
                    continue
                texts.append(sentence)
                owners.append(paper_id)
                per_paper[paper_id] += 1
    stats, groups = dedup_stats(texts, owners, threshold=threshold)
    return stats, groups, per_paper


def fmt(value: float) -> str:
    return f"{value * 100:.2f}%"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    args = parser.parse_args(argv)

    rows = ledger_rows()
    total_calls = sum(int(row["calls"]) for row in rows)
    total_hits = sum(int(row["cache_hits"]) for row in rows)
    total_priced_hits = sum(int(row["priced_hits"]) for row in rows)
    probe = next((row for row in rows if row["run_id"] == PROBE_RUN), None)
    cache_count = cache_size()

    papers = baseline_papers()
    print(f"papers {len(papers)}; computing exact census ...")
    stats_90, groups_90, per_paper = census(papers, NEAR_DUPLICATE_THRESHOLD)
    print(f"threshold {NEAR_DUPLICATE_THRESHOLD}: {stats_90}")
    print("computing sensitivity census at 0.8 ...")
    stats_80, _, _ = census(papers, 0.8)
    print(f"threshold 0.8: {stats_80}")

    # Repeated-cluster sizes only; no source text in the tracked report.
    sizes = Counter(len(group.members) for group in groups_90 if len(group.members) > 1)
    largest = sorted(
        (len(group.members) for group in groups_90 if len(group.members) > 1), reverse=True
    )[:10]

    lines = [
        "# P2-04 — cache and near-duplicate census",
        "",
        f"> Generated by `python scripts/cache_dedup_report.py` on "
        f"{datetime.now(UTC).strftime('%Y-%m-%d')}. No LLM call; ledger read-only.",
        "",
        "## 1. Response cache (measured)",
        "",
        "The client keys the cache over the rendered prompt, system prompt, model, "
        "temperature, max output tokens, response schema and thinking level "
        "(`src/axion/llm/cache.py`). A hit is written to the ledger with `cache_hit=1`, "
        "zero prompt/completion tokens and `usd=0`.",
        "",
        "| Run | Ledger rows | Cache hits | Hit rate | List price | Hits with cost |",
        "| :-- | --: | --: | --: | --: | --: |",
    ]
    for row in rows:
        calls = int(row["calls"])
        hits = int(row["cache_hits"])
        lines.append(
            f"| `{row['run_id']}` | {calls} | {hits} | {fmt(hits / calls) if calls else 'n/a'} | "
            f"${float(row['usd'] or 0):.6f} | {int(row['priced_hits'])} |"
        )
    lines += [
        f"| **all runs** | **{total_calls}** | **{total_hits}** | "
        f"**{fmt(total_hits / total_calls) if total_calls else 'n/a'}** | "
        f"**${sum(float(row['usd'] or 0) for row in rows):.6f}** | "
        f"**{total_priced_hits}** |",
        "",
        "- Ledger rows include retried provider attempts, so the hit rate is over attempts, "
        "not over distinct papers.",
        f"- Cache rows before and after the probe: **{cache_count}** (the probe added none, "
        "so every probe call was a read hit).",
        "- Every cache-hit ledger row has `usd = 0` and zero prompt/completion tokens: "
        f"**{total_priced_hits}** priced hits across all runs.",
        "",
        "### Re-run probe",
        "",
        f"Command (run 2026-11-17, no provider call): `AXION_DRY_RUN=false python "
        f"scripts/run_baseline_extraction.py --execute --sample 5 --run-id {PROBE_RUN}`.",
        "",
    ]
    if probe is None:
        lines.append("- Probe row not found in the ledger.")
    else:
        lines += [
            f"- **{int(probe['calls'])} calls, {int(probe['cache_hits'])} cache hits "
            f"({fmt(int(probe['cache_hits']) / int(probe['calls']))}), "
            f"list price ${float(probe['usd'] or 0):.6f}, zero tokens.**",
            "- The five papers are a prefix of the frozen baseline sample, so their prompts "
            "were already cached by `p1-10-flashlite-s20261114-n100`.",
            "- This is the strongest cache evidence available: the same prompts were replayed "
            "end-to-end and the ledger recorded five zero-cost hits.",
        ]
    lines += [
        "",
        "## 2. Sentence repetition (measured, 100-paper baseline sample)",
        "",
        f"- Papers: **{len(papers)}**; sentences (>= {MIN_CHARS} chars): "
        f"**{stats_90.sentences:,}**.",
        f"- Duplicate sentences (copies beyond the first): **{stats_90.duplicate_sentences:,}** "
        f"({fmt(stats_90.duplicate_sentences / max(stats_90.sentences, 1))}).",
        f"- Of those, **{stats_90.exact_duplicate_sentences:,} exact** normalized copies and "
        f"**{stats_90.near_duplicate_sentences:,} near-duplicates** "
        f"(Jaccard >= {stats_90.threshold}).",
        f"- Cross-paper copies: **{stats_90.cross_paper_duplicate_sentences:,}**; "
        f"within-paper copies: **{stats_90.within_paper_duplicate_sentences:,}**.",
        f"- Duplicate characters: **{stats_90.duplicate_chars:,}** ≈ "
        f"**{stats_90.estimated_tokens_saved:,} prompt tokens** at 4 chars/token "
        "(a projection, not a measured run).",
        f"- Duplicate groups: **{stats_90.duplicate_groups:,}**; largest group "
        f"**{largest[0] if largest else 0}** copies; group-size histogram "
        f"{dict(sorted(sizes.items()))}.",
        "",
        "Sensitivity (same input, weaker near-duplicate threshold):",
        "",
        "| Threshold | Duplicate sentences | Exact | Near | Cross-paper | Est. tokens |",
        "| --: | --: | --: | --: | --: | --: |",
        f"| {stats_90.threshold} | {stats_90.duplicate_sentences:,} | "
        f"{stats_90.exact_duplicate_sentences:,} | {stats_90.near_duplicate_sentences:,} | "
        f"{stats_90.cross_paper_duplicate_sentences:,} | {stats_90.estimated_tokens_saved:,} |",
        f"| {stats_80.threshold} | {stats_80.duplicate_sentences:,} | "
        f"{stats_80.exact_duplicate_sentences:,} | {stats_80.near_duplicate_sentences:,} | "
        f"{stats_80.cross_paper_duplicate_sentences:,} | {stats_80.estimated_tokens_saved:,} |",
        "",
        "## 3. What this does and does not buy",
        "",
        "- **Cache:** a repeated prompt costs **$0** and consumes no provider quota. This is "
        "measured; it is the cheapest lever and it is already on for every run. Its value at "
        "corpus scale depends on re-processing: a paper is processed once (lazy), so the cache "
        "primarily protects resumed runs and prompt-identical repeats.",
        "- **Dedup:** the census is a measurement, not a prompt change. Removing duplicate "
        "sentences from prompts would change the baseline's evidence and needs its own live "
        "separation run plus a quality row; the token estimate above is therefore an **upper "
        "bound on avoidable text**, not a claimed saving. Within-paper duplicates ("
        f"{stats_90.within_paper_duplicate_sentences:,}) are the safer first target because they "
        "cannot remove a unique claim.",
        "- Near-duplicate detection is approximate: MinHash/LSH proposes candidates and Jaccard "
        "verifies them; a pair can be missed if no band collides. Exact counts are exact.",
        "- The census covers the frozen 100-paper baseline sample (the papers with cached full "
        "text), not the whole 4,928-paper corpus. Corpus-wide rates are unknown.",
        "",
        "## Limits (repeat in every P2 report)",
        "",
        "- Gold measures precision only; retention is agreement with the baseline's own audited "
        "output, not recall. Unverifiable output is never counted as correct.",
        "- This report contains no quality claim: it isolates cache and repetition.",
        "- No model was adopted and the P1 baseline remains frozen.",
        "",
    ]
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"report {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
