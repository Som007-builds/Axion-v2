"""Validate and summarize the P3-01 dependency pilot labels.

The pilot is calibration only: it is not gold, not training data, and not an
evaluation set. This script reads the returned labelled CSV, checks the label
vocabulary, and writes a reproducible Markdown/JSON summary. It never creates
or changes labels.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
from collections import Counter
from pathlib import Path

ALLOWED_LABELS = {"RELIES_ON", "MENTIONS", "UNRELATED"}
REQUIRED_COLUMNS = {
    "pilot_id",
    "source_pmcid",
    "section",
    "context_text",
    "source_claim_text",
    "label",
    "note",
    "labeler",
    "date",
    "guideline_version",
}


def _read(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames is None:
            raise SystemExit(f"{path}: missing CSV header")
        missing = REQUIRED_COLUMNS - set(reader.fieldnames)
        if missing:
            raise SystemExit(f"{path}: missing columns {sorted(missing)}")
        return list(reader)


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _section_bucket(section: str) -> str:
    text = section.strip()
    if not text:
        return "(blank)"
    lowered = text.lower()
    if "introduction" in lowered:
        return "Introduction"
    if "discussion" in lowered:
        return "Discussion"
    if "results" in lowered:
        return "Results"
    if "genomic" in lowered:
        return "Genomic surveillance"
    return text


def _kappa(
    rows: list[dict[str, str]], second: dict[str, dict[str, str]]
) -> tuple[int, float, float | None]:
    paired = [
        (row["label"].strip(), second[row["pilot_id"]]["label"].strip())
        for row in rows
        if row["pilot_id"] in second
        and row["label"].strip() in ALLOWED_LABELS
        and second[row["pilot_id"]]["label"].strip() in ALLOWED_LABELS
    ]
    if not paired:
        return 0, 0.0, None
    n = len(paired)
    matches = sum(left == right for left, right in paired)
    raw = matches / n
    left_counts = Counter(left for left, _ in paired)
    right_counts = Counter(right for _, right in paired)
    expected = sum((left_counts[label] / n) * (right_counts[label] / n) for label in ALLOWED_LABELS)
    if expected >= 1.0:
        return n, raw, None
    return n, raw, (raw - expected) / (1.0 - expected)


def _fmt_counts(counter: Counter[str]) -> str:
    return " · ".join(f"`{key}` {value}" for key, value in sorted(counter.items()))


def _fmt_pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def _build_report(
    labelled_path: Path,
    rows: list[dict[str, str]],
    second_path: Path | None,
    second: dict[str, dict[str, str]] | None,
) -> str:
    labels = Counter(row["label"].strip() or "(blank)" for row in rows)
    labelers = Counter(row["labeler"].strip() or "(blank)" for row in rows)
    dates = Counter(row["date"].strip() or "(blank)" for row in rows)
    versions = Counter(row["guideline_version"].strip() or "(blank)" for row in rows)
    sections = Counter(_section_bucket(row["section"]) for row in rows)
    notes = sum(bool(row["note"].strip()) for row in rows)
    blank = [row["pilot_id"] for row in rows if not row["label"].strip()]
    retraction = [row["pilot_id"] for row in rows if "retraction" in row["note"].lower()]
    reference_fragment = [
        row["pilot_id"] for row in rows if "reference-list fragment" in row["note"].lower()
    ]
    corroboration = [
        row["pilot_id"]
        for row in rows
        if "corrobor" in row["note"].lower() or "consisten" in row["note"].lower()
    ]
    corrections = [
        (row["pilot_id"], row["note"]) for row in rows if "corrected from" in row["note"].lower()
    ]
    missing_claim = [row["pilot_id"] for row in rows if not row["source_claim_text"].strip()]

    lines = [
        "# P3-01 dependency pilot — measured summary",
        "",
        "**Status:** calibration pilot only. Not gold, not training data, "
        "and not an evaluation result.",
        "",
        "## Inputs and provenance",
        "",
        "- Generated by: `python scripts/dependency_pilot_metrics.py`",
        f"- Labelled packet: `{labelled_path.as_posix()}`",
        f"- SHA-256: `{_sha256(labelled_path)}`",
        f"- Rows: **{len(rows)}** across "
        f"**{len({row['source_pmcid'] for row in rows})}** source papers",
        f"- Labeler(s): {_fmt_counts(labelers)}",
        "- Responsibility: the project owner accepts responsibility for the pilot labels.",
        f"- Date(s): {_fmt_counts(dates)}",
        f"- Guideline version(s): {_fmt_counts(versions)}",
        "",
        "## Label distribution",
        "",
        "| Label | n | share |",
        "| :-- | --: | --: |",
    ]
    for label, count in sorted(labels.items()):
        lines.append(f"| {label} | {count} | {_fmt_pct(count / len(rows))} |")
    lines += [
        "",
        f"- Notes filled: **{notes}/{len(rows)}**",
        f"- Blank labels: **{len(blank)}**" + (f" ({', '.join(blank)})" if blank else ""),
        f"- Rows mentioning retraction: {len(retraction)} ({', '.join(retraction) or '—'})",
        f"- Rows mentioning a reference-list fragment: {len(reference_fragment)} "
        f"({', '.join(reference_fragment) or '—'})",
        f"- Rows mentioning corroboration/consistency: {len(corroboration)} "
        f"({', '.join(corroboration) or '—'})",
        f"- Rows with no source-claim proxy: {len(missing_claim)} "
        f"({', '.join(missing_claim) or '—'})",
        "",
        "## Section mix",
        "",
        "| Section bucket | n |",
        "| :-- | --: |",
    ]
    for section, count in sorted(sections.items()):
        lines.append(f"| {section} | {count} |")

    lines += ["", "## Agreement", ""]
    if second is None:
        lines.append(
            "No second-labeler file was supplied. Raw agreement and Cohen's κ are "
            "**not estimable**; this is a single-labeler calibration pilot. Do not report it as "
            "inter-labeler agreement or as a gold result."
        )
    else:
        n, raw, kappa = _kappa(rows, second)
        kappa_text = "not estimable (degenerate marginals)" if kappa is None else f"{kappa:.3f}"
        lines.append(
            f"Second-labeler overlap: **n={n}**, raw agreement **{_fmt_pct(raw)}**, "
            f"Cohen's κ **{kappa_text}** "
            f"(`{second_path.as_posix() if second_path else '(unknown)'}`)."
        )

    lines += ["", "## Review signals", ""]
    if corrections:
        for pilot_id, note in corrections:
            lines.append(f"- `{pilot_id}`: note says the row was corrected during review — {note}")
        ids = ", ".join(f"`{pilot_id}`" for pilot_id, _ in corrections)
        lines += [
            "",
            f"{len(corrections)} row(s) were reclassified from `RELIES_ON` to `MENTIONS` during "
            f"review ({ids}). The final labels are `MENTIONS`; this is the pilot evidence that "
            "grouped discussion corroboration needed an explicit guideline rule. The notes are "
            "retained verbatim in the CSV.",
        ]
    else:
        lines.append("- No notes mention a correction during review.")
    lines += [
        "",
        "## Scope reminder",
        "",
        "- P3-03 draws a fresh stratified sample; this packet is not reused as gold.",
        "- No student or teacher label is converted into gold.",
        "- The `insufficient_context` UI action would export as a blank label plus a note; this "
        "pilot has none.",
        "",
    ]
    return "\n".join(lines)


def _build_json(rows: list[dict[str, str]], report_path: Path) -> dict[str, object]:
    labels = Counter(row["label"].strip() or "" for row in rows)
    return {
        "pilot": "P3-01",
        "status": "calibration_only",
        "responsibility": "owner",
        "rows": len(rows),
        "sources": len({row["source_pmcid"] for row in rows}),
        "labels": dict(sorted(labels.items())),
        "notes_filled": sum(bool(row["note"].strip()) for row in rows),
        "blank_labels": [row["pilot_id"] for row in rows if not row["label"].strip()],
        "labelers": dict(sorted(Counter(row["labeler"] for row in rows).items())),
        "dates": dict(sorted(Counter(row["date"] for row in rows).items())),
        "guideline_versions": dict(
            sorted(Counter(row["guideline_version"] for row in rows).items())
        ),
        "report": report_path.as_posix(),
    }


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--labelled",
        type=Path,
        default=root / "eval/audit/dependency_pilot_v1_labelled.csv",
    )
    parser.add_argument("--second", type=Path, default=None)
    parser.add_argument(
        "--out",
        type=Path,
        default=root / "docs/reports/P3-01-pilot.md",
    )
    parser.add_argument(
        "--json-out",
        type=Path,
        default=root / "eval/audit/dependency_pilot_v1.summary.json",
    )
    args = parser.parse_args()

    rows = _read(args.labelled)
    invalid = sorted({row["label"].strip() for row in rows} - ALLOWED_LABELS - {""})
    if invalid:
        raise SystemExit(f"invalid labels: {invalid}")
    if len({row["pilot_id"] for row in rows}) != len(rows):
        raise SystemExit("duplicate pilot_id values")

    second: dict[str, dict[str, str]] | None = None
    if args.second is not None:
        second = {row["pilot_id"]: row for row in _read(args.second)}

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        _build_report(args.labelled, rows, args.second, second),
        encoding="utf-8",
    )
    args.json_out.parent.mkdir(parents=True, exist_ok=True)
    args.json_out.write_text(
        json.dumps(_build_json(rows, args.out), indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {args.out} and {args.json_out}")


if __name__ == "__main__":
    main()
