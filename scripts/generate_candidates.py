"""Generate and load the P3-02 deterministic candidate-context graph.

The script reads the ID-only P1 manifest and the untracked JATS cache, collects
every citation context whose reference resolves to a retracted/flagged source
paper, writes per-source counts, and loads the candidate graph into Neo4j. It
also creates one deterministic abstract-sentence source-claim proxy per source;
the proxy is a P3-06 placeholder, not a gold claim and not a dependency label.

No LLM, network, embedding, or Chroma calls are made.

Usage:
    python scripts/generate_candidates.py --twice
    python scripts/generate_candidates.py --in-memory --twice
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

from axion.config.settings import Settings
from axion.ingest.corpus import (
    CorpusCite,
    CorpusManifest,
    CorpusPaper,
    read_cites_csv,
    read_manifest,
    read_papers_csv,
    sha256_file,
)
from axion.link.candidates import (
    CandidateBundle,
    CandidateError,
    CandidateLoadResult,
    build_candidates,
    load_candidates,
    validate_source_counts,
)
from axion.store.base import StoreConfigurationError
from axion.store.memory import InMemoryGraph
from axion.store.neo4j import Neo4jBackend

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MANIFEST = ROOT / "docs" / "reports" / "P1-corpus-manifest.json"
DEFAULT_CACHE = ROOT / "data" / "raw" / "europepmc"
DEFAULT_COUNTS = ROOT / "docs" / "reports" / "P3-02-candidate-counts.csv"
DEFAULT_REPORT = ROOT / "docs" / "reports" / "P3-02-candidates.md"


def _write_counts(path: Path, bundle: CandidateBundle) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(
            [
                "source_pmcid",
                "candidate_contexts",
                "citer_papers",
                "has_source_claim",
                "source_claim_id",
            ]
        )
        for row in bundle.source_counts:
            writer.writerow(
                [
                    row.source_pmcid,
                    row.candidate_contexts,
                    row.citer_papers,
                    str(row.has_source_claim).lower(),
                    row.source_claim_id,
                ]
            )


def _graph_counts_table(counts: dict[str, int]) -> str:
    return "\n".join(
        ["| Item | Count |", "| :-- | --: |"]
        + [f"| `{name}` | {count} |" for name, count in sorted(counts.items())]
    )


def _render_report(
    *,
    bundle: CandidateBundle,
    manifest_path: Path,
    manifest_config_sha256: str,
    papers_sha256: str,
    cites_sha256: str,
    backend: str,
    run_id: str,
    first: CandidateLoadResult,
    second: CandidateLoadResult | None,
) -> str:
    totals = bundle.totals
    with_claim_pct = (
        100.0 * totals.contexts_with_source_claim / totals.candidate_contexts
        if totals.candidate_contexts
        else 0.0
    )
    top = sorted(
        bundle.source_counts,
        key=lambda row: (-row.candidate_contexts, row.source_pmcid),
    )[:20]
    top_rows = "\n".join(
        "| "
        + " | ".join(
            [
                f"`{row.source_pmcid}`",
                str(row.candidate_contexts),
                str(row.citer_papers),
                "yes" if row.has_source_claim else "no",
            ]
        )
        + " |"
        for row in top
    )
    idempotent = (
        "not checked"
        if second is None
        else ("yes - graph counts identical" if first.graph_counts == second.graph_counts else "NO")
    )
    return f"""# P3-02 candidate generator - measured counts

**Status:** complete; deterministic, no LLM calls, real spend $0.
**Generated by:** `python scripts/generate_candidates.py --twice`
**Backend:** `{backend}` | **Run ID:** `{run_id}`

## Inputs

- Manifest: `{manifest_path}`
- Manifest config SHA-256: `{manifest_config_sha256}`
- Papers CSV SHA-256: `{papers_sha256}`
- Cites CSV SHA-256: `{cites_sha256}`
- Full text: untracked JATS cache; this report contains no context text.

## Candidate counts

| Measure | Count |
| :-- | --: |
| Source papers with >=1 citer edge | {totals.source_papers_with_citers} |
| Source papers with >=1 candidate context | {totals.source_papers_with_contexts} |
| Source papers with zero candidate contexts | {totals.source_papers_without_contexts} |
| Candidate contexts | {totals.candidate_contexts} |
| Citer papers with >=1 candidate context | {totals.citer_papers} |
| Source-claim proxies (one abstract sentence per source) | {totals.source_claim_proxies} |
| Candidate contexts with a source-claim pointer | {totals.contexts_with_source_claim} |
| Candidate contexts without a source-claim pointer | {totals.contexts_without_source_claim} |
| Share with a source-claim pointer | {with_claim_pct:.1f}% |

The source-claim pointer is a coarse, rule-based placeholder: the first
substantive sentence of the source paper's abstract. It is **not** a specific
claim match, not a dependency label, and not gold. P3-06 owns claim linking.

## Per-source counts

The full 285-row table is in `docs/reports/P3-02-candidate-counts.csv` (one row
per source paper with a citer edge). Top 20 by context count:

| Source | Contexts | Citer papers | Source-claim proxy |
| :-- | --: | --: | :-- |
{top_rows}

## Graph load

| Measure | Rows |
| :-- | --: |
| Paper rows | {first.paper_rows} |
| Retraction notice rows | {first.notice_rows} |
| Cite rows | {first.cite_rows} |
| Candidate context rows | {first.candidate_rows} |
| Source-claim-proxy rows | {first.source_claim_rows} |
| Idempotent second run | {idempotent} |

{_graph_counts_table(first.graph_counts)}

## Reproducibility

- Command: `python scripts/generate_candidates.py --twice`
- The candidate key is the parser's stable context ID (`paper:p:s:c`), so a
  re-run MERGEs the same nodes and relationships.
- The script validates candidate totals against the P1 manifest and
  per-source totals against `P1-corpus-cites.csv`; a mismatch fails loudly.
- No labels were created. P3-03 draws a fresh stratified sample.

## Limits

- Counts are conditional on the P1 citer set. **5,734 eligible citers were
  truncated by the 5,000-paper corpus cap**, so these counts are a lower bound.
- 27 of the 285 source papers with a citer edge have zero linked contexts in
  the committed manifest; they are still reported, at zero, in the CSV.
- A source-claim proxy exists only when the source abstract yields a usable
  sentence. Missing proxies are reported, not silently filled.
- Contexts are candidate rows for later detection; their presence is not a
  claim that the citing paper depends on the source.
"""


def _read_inputs(
    manifest_path: Path,
) -> tuple[
    CorpusManifest,
    list[CorpusPaper],
    list[CorpusCite],
    str,
    str,
    str,
    str,
]:
    manifest = read_manifest(manifest_path)
    papers_path = manifest_path.parent / Path(manifest.files.papers_csv).name
    cites_path = manifest_path.parent / Path(manifest.files.cites_csv).name
    papers_sha = sha256_file(papers_path)
    cites_sha = sha256_file(cites_path)
    if papers_sha != manifest.files.papers_sha256:
        raise CandidateError(f"paper manifest hash mismatch: {papers_path}")
    if cites_sha != manifest.files.cites_sha256:
        raise CandidateError(f"citation manifest hash mismatch: {cites_path}")
    papers = read_papers_csv(papers_path)
    cites = read_cites_csv(cites_path)
    return (
        manifest,
        papers,
        cites,
        manifest.config_sha256,
        papers_sha,
        cites_sha,
        f"p3-02-candidates-{manifest.config_sha256[:12]}",
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--cache-dir", type=Path, default=DEFAULT_CACHE)
    parser.add_argument("--counts-out", type=Path, default=DEFAULT_COUNTS)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--run-id", type=str, default=None)
    parser.add_argument("--in-memory", action="store_true")
    parser.add_argument("--twice", action="store_true")
    parser.add_argument(
        "--allow-missing-fulltext",
        action="store_true",
        help="skip unparseable papers instead of failing (diagnostic only)",
    )
    parser.add_argument(
        "--allow-count-mismatch",
        action="store_true",
        help="write counts even when they differ from the P1 manifest (diagnostic only)",
    )
    args = parser.parse_args(argv)

    try:
        (
            manifest,
            papers,
            cites,
            config_sha,
            papers_sha,
            cites_sha,
            default_run_id,
        ) = _read_inputs(args.manifest)
        expected_contexts = None if args.allow_count_mismatch else manifest.counts.contexts_total
        bundle = build_candidates(
            papers,
            cites,
            cache_dir=args.cache_dir,
            require_fulltext=not args.allow_missing_fulltext,
            expected_contexts=expected_contexts,
        )
        if not args.allow_count_mismatch:
            validate_source_counts(cites, bundle)
        run_id = args.run_id or default_run_id
        if args.in_memory:
            graph = InMemoryGraph()
            backend = "in-memory"
        else:
            settings = Settings()
            if not (settings.neo4j_uri and settings.neo4j_username and settings.neo4j_password):
                raise StoreConfigurationError(
                    "Neo4j settings are missing; set NEO4J_URI, NEO4J_USERNAME, NEO4J_PASSWORD"
                )
            graph = Neo4jBackend(
                settings.neo4j_uri,
                settings.neo4j_username,
                settings.neo4j_password.get_secret_value(),
            )
            backend = settings.neo4j_uri
        try:
            first = load_candidates(bundle, graph=graph, run_id=run_id)
            second = load_candidates(bundle, graph=graph, run_id=run_id) if args.twice else None
            if second is not None and first.graph_counts != second.graph_counts:
                raise CandidateError(
                    "candidate load is not idempotent: graph counts changed on second load"
                )
        finally:
            graph.close()
    except (CandidateError, StoreConfigurationError, ValueError) as exc:
        print(f"candidate generation failed: {exc}", file=sys.stderr, flush=True)
        return 1

    _write_counts(args.counts_out, bundle)
    report = _render_report(
        bundle=bundle,
        manifest_path=args.manifest,
        manifest_config_sha256=config_sha,
        papers_sha256=papers_sha,
        cites_sha256=cites_sha,
        backend=backend,
        run_id=run_id,
        first=first,
        second=second,
    )
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(report, encoding="utf-8", newline="\n")
    summary = {
        "backend": backend,
        "run_id": run_id,
        "idempotent": first.graph_counts == second.graph_counts if second else None,
        "candidate_contexts": bundle.totals.candidate_contexts,
        "source_papers_with_citers": bundle.totals.source_papers_with_citers,
        "source_papers_with_contexts": bundle.totals.source_papers_with_contexts,
        "source_papers_without_contexts": bundle.totals.source_papers_without_contexts,
        "source_claim_proxies": bundle.totals.source_claim_proxies,
        "contexts_with_source_claim": bundle.totals.contexts_with_source_claim,
        "graph_counts": first.graph_counts,
    }
    print(json.dumps(summary, indent=2, sort_keys=True), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
