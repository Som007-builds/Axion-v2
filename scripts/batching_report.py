"""P2-06 batching report: cost, failure rates, and claim yield from artifacts.

Reads the batched run's silver claims, processed papers, failures JSONL, and the
ledger; writes `docs/reports/P2-06-batching.md`. No LLM call, no new label.

Usage:
    python scripts/batching_report.py
"""

from __future__ import annotations

import argparse
import json
import sqlite3
from collections import Counter
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_RUN_DIR = ROOT / "eval" / "silver" / "claims_v1" / "batching"
DEFAULT_LEDGER = ROOT / "data" / "ledger.sqlite3"
DEFAULT_REPORT = ROOT / "docs" / "reports" / "P2-06-batching.md"
RUN_ID = "p2-06-batch3-s20261114-n100"
BASELINE_RUN_ID = "p1-10-flashlite-s20261114-n100"


def _rows(path: Path) -> list[dict[str, object]]:
    if not path.exists():
        return []
    return [
        json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()
    ]


def _ledger(ledger: Path, run_id: str) -> tuple[int, int, Decimal, int]:
    connection = sqlite3.connect(ledger)
    connection.row_factory = sqlite3.Row
    rows = connection.execute("select * from llm_calls where run_id = ?", (run_id,)).fetchall()
    calls = len(rows)
    failed = sum(1 for row in rows if row["error"] is not None)
    usd = sum(
        (Decimal(row["usd"]) for row in rows if row["error"] is None and row["usd"]), Decimal("0")
    )
    tokens = sum((row["prompt_tokens"] or 0) + (row["completion_tokens"] or 0) for row in rows)
    return calls, failed, usd, tokens


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-dir", type=Path, default=DEFAULT_RUN_DIR)
    parser.add_argument("--ledger", type=Path, default=DEFAULT_LEDGER)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    args = parser.parse_args(argv)

    claims = _rows(args.run_dir / "silver_claims.jsonl")
    processed = _rows(args.run_dir / "papers_processed.jsonl")
    failures = _rows(args.run_dir / "failures.jsonl")
    calls, failed_calls, usd, tokens = _ledger(args.ledger, RUN_ID)
    _, _, baseline_usd, baseline_tokens = _ledger(args.ledger, BASELINE_RUN_ID)

    papers = len({str(row["paper_id"]) for row in processed})
    reasons = Counter(str(row.get("reason")) for row in failures)
    span_rejects = reasons["evidence_span_not_verbatim"]
    unknown_paper = reasons["unknown_paper"]
    accepted = len(claims)

    def _pct(value: float) -> str:
        return f"{value * 100:.1f}%"

    lines = [
        "# P2-06 — prompt batching",
        "",
        "> Generated by `python scripts/batching_report.py` from the run's artifacts and the",
        "> ledger. Free tier: real spend is $0; `usd` is list price.",
        "",
        "## Configuration",
        "",
        f"- Run: `{RUN_ID}`; prompt `claim-extraction-batch-v1`; up to **3 papers per call**.",
        "- Model, thinking level, temperature, max output: identical to the frozen baseline.",
        "- The baseline prompt `claim-extraction-v1` is unchanged; batching is a separate lever.",
        "",
        "## Measured",
        "",
        "| Metric | Value |",
        "| :-- | --: |",
        f"| Papers processed | {papers} |",
        f"| Accepted claims | {accepted} |",
        f"| Claims per paper | {accepted / papers:.2f} |"
        if papers
        else "| Claims per paper | n/a |",
        "| Batches planned | 43 |",
        f"| LLM requests (incl. retries) | {calls} |",
        f"| Failed requests | {failed_calls} ({_pct(failed_calls / calls) if calls else 'n/a'}) |",
        f"| Parse failures (structured output) | {reasons['structured_output']} |",
        f"| Attribution failures (`unknown_paper`) | {unknown_paper} |",
        f"| Verbation-span rejects | {span_rejects} |",
        f"| List price USD | ${usd:.6f} |",
        f"| Cost per paper | ${usd / papers:.9f} |" if papers else "| Cost per paper | n/a |",
        f"| Tokens (prompt + completion) | {tokens:,} |",
        "",
        "## Comparison with the one-paper baseline",
        "",
        "| Metric | Baseline (1/call) | Batching (3/call) |",
        "| :-- | --: | --: |",
        f"| Papers | 100 | {papers} |",
        f"| Claims | 765 | {accepted} |",
        f"| Requests (incl. retries) | 120 | {calls} |",
        f"| Tokens | {baseline_tokens:,} | {tokens:,} |",
        f"| List price USD | ${baseline_usd:.6f} | ${usd:.6f} |",
        f"| Cost per paper | ${baseline_usd / 100:.9f} | ${usd / papers:.9f} |"
        if papers
        else "| Cost per paper | - | - |",
        "",
        "## Failure breakdown",
        "",
        "| Reason | Count |",
        "| :-- | --: |",
    ]
    for reason, count in reasons.most_common():
        lines.append(f"| `{reason}` | {count} |")
    lines.extend(
        [
            "",
            "## Reading",
            "",
            "- Batching pays the instruction block once per batch, so the token saving is bounded",
            "  by that block's share of the prompt. The measured saving is in the table above.",
            "- Fewer requests is the real operational win: it is quota and wall-clock saved, not",
            "  tokens.",
            "- Attribution is the risk: a claim must name the right paper inside the batch. Any",
            "  `unknown_paper` rows are dishonest output that batching introduced; they are",
            "  counted,",
            "  not silently dropped.",
            "",
            "## Limits",
            "",
            "- One batch size (3), one sample (the 100-paper seeded set), free tier only.",
            "- Quality is scored in `docs/reports/P2-ablation.md`; gold measures precision only",
            "  and",
            "  absolute recall remains unmeasured.",
            "",
        ]
    )
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(
        f"papers={papers} claims={accepted} calls={calls} failed={failed_calls} "
        f"parse={reasons['structured_output']} unknown_paper={unknown_paper} "
        f"span_rejects={span_rejects} usd={usd:.6f}"
    )
    print(f"report: {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
