"""Provider reliability from the cost ledger: per-request outcomes, hourly rates.

Every ledger row is one attempt (a retry is a separate row), so the 503/5xx
rates below are *request* rates, not paper rates. Times are reported in UTC and
in America/Los_Angeles so a run window can be chosen deliberately.

Usage:
    python scripts/provider_reliability.py
    python scripts/provider_reliability.py --report docs/reports/P2-provider-reliability.md
"""

from __future__ import annotations

import argparse
import csv
import sqlite3
from collections import Counter, defaultdict
from datetime import UTC, datetime
from pathlib import Path
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_LEDGER = ROOT / "data" / "ledger.sqlite3"
DEFAULT_REPORT = ROOT / "docs" / "reports" / "P2-provider-reliability.md"
DEFAULT_CSV = ROOT / "docs" / "reports" / "P2-provider-reliability.csv"
PACIFIC = ZoneInfo("America/Los_Angeles")


def _parse_ts(text: str) -> datetime:
    value = datetime.fromisoformat(text.replace("Z", "+00:00"))
    if value.tzinfo is None:
        value = value.replace(tzinfo=UTC)
    return value.astimezone(UTC)


def _outcome(error: str | None, error_class: str | None, http_status: int | None) -> str:
    if error is None:
        return "ok"
    status = f"HTTP {http_status}" if http_status else "no status"
    return f"{error_class or 'error'} ({status})"


def _is_5xx(status: int | None) -> bool:
    return status is not None and 500 <= status <= 599


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ledger", type=Path, default=DEFAULT_LEDGER)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--csv", type=Path, default=DEFAULT_CSV)
    args = parser.parse_args(argv)

    if not args.ledger.exists():
        print(f"missing ledger: {args.ledger}")
        return 1

    connection = sqlite3.connect(args.ledger)
    connection.row_factory = sqlite3.Row
    rows = connection.execute(
        "select id, ts, run_id, model, paper_id, error, error_class, http_status, latency_ms "
        "from llm_calls order by id"
    ).fetchall()
    if not rows:
        print("ledger has no calls")
        return 1

    records: list[dict[str, object]] = []
    by_hour: dict[tuple[str, int], Counter[str]] = defaultdict(Counter)
    by_run: dict[str, Counter[str]] = defaultdict(Counter)
    by_model: dict[str, Counter[str]] = defaultdict(Counter)
    for row in rows:
        when = _parse_ts(row["ts"])
        pacific = when.astimezone(PACIFIC)
        outcome = _outcome(row["error"], row["error_class"], row["http_status"])
        status = row["http_status"]
        key = (pacific.strftime("%Y-%m-%d"), pacific.hour)
        for bucket in (by_hour[key], by_run[row["run_id"] or "-"], by_model[row["model"] or "-"]):
            bucket["total"] += 1
            if outcome != "ok":
                bucket["failed"] += 1
            if _is_5xx(status):
                bucket["5xx"] += 1
            if status == 503:
                bucket["503"] += 1
        records.append(
            {
                "id": row["id"],
                "ts_utc": when.strftime("%Y-%m-%dT%H:%M:%SZ"),
                "ts_pacific": pacific.strftime("%Y-%m-%d %H:%M:%S %Z"),
                "run_id": row["run_id"] or "",
                "model": row["model"] or "",
                "paper_id": row["paper_id"] or "",
                "outcome": outcome,
                "http_status": status if status is not None else "",
                "latency_ms": row["latency_ms"] if row["latency_ms"] is not None else "",
            }
        )

    args.csv.parent.mkdir(parents=True, exist_ok=True)
    with args.csv.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(records[0]))
        writer.writeheader()
        writer.writerows(records)

    total = len(records)
    failures = sum(1 for record in records if record["outcome"] != "ok")
    fives = sum(1 for record in records if _is_5xx(record["http_status"] or None))
    five_oh_three = sum(1 for record in records if record["http_status"] == 503)

    def _rate(part: int, whole: int) -> str:
        return f"{part / whole:.1%}" if whole else "n/a"

    lines = [
        "# P2 provider reliability",
        "",
        "> Generated by `python scripts/provider_reliability.py` from `data/ledger.sqlite3`.",
        "> One row in the ledger is one **attempt**; a retry is a separate attempt, so these",
        "> are request rates, not paper rates. Times are America/Los_Angeles (Pacific) and UTC.",
        "",
        "## Overall",
        "",
        f"- Requests recorded: **{total}**",
        f"- Failed attempts: **{failures}** ({_rate(failures, total)})",
        f"- 5xx responses: **{fives}** ({_rate(fives, total)})",
        f'- HTTP 503 (`UNAVAILABLE`, "high demand"): **{five_oh_three}** '
        f"({_rate(five_oh_three, total)})",
        "",
        "## By model",
        "",
        "| Model | Requests | Failed | Fail rate | 5xx | 503 rate |",
        "| :-- | --: | --: | --: | --: | --: |",
    ]
    for model, bucket in sorted(by_model.items()):
        lines.append(
            f"| `{model}` | {bucket['total']} | {bucket['failed']} | "
            f"{_rate(bucket['failed'], bucket['total'])} | {bucket['5xx']} | "
            f"{_rate(bucket['503'], bucket['total'])} |"
        )
    lines.extend(
        [
            "",
            "## By run",
            "",
            "| Run | Requests | Failed | Fail rate | 5xx | 503 rate |",
            "| :-- | --: | --: | --: | --: | --: |",
        ]
    )
    for run, bucket in sorted(by_run.items()):
        lines.append(
            f"| `{run}` | {bucket['total']} | {bucket['failed']} | "
            f"{_rate(bucket['failed'], bucket['total'])} | {bucket['5xx']} | "
            f"{_rate(bucket['503'], bucket['total'])} |"
        )
    lines.extend(
        [
            "",
            "## By Pacific hour",
            "",
            "| Pacific date | Pacific hour | UTC hour | Requests | Failed | Fail rate | 5xx "
            "| 503 rate |",
            "| :-- | --: | --: | --: | --: | --: | --: | --: |",
        ]
    )
    for key in sorted(by_hour):
        day, hour = key
        bucket = by_hour[key]
        sample = next(r for r in records if str(r["ts_pacific"]).startswith(f"{day} {hour:02d}"))
        utc_hour = str(sample["ts_utc"])[11:16]
        lines.append(
            f"| {day} | {hour:02d} | {utc_hour}Z | {bucket['total']} | {bucket['failed']} | "
            f"{_rate(bucket['failed'], bucket['total'])} | {bucket['5xx']} | "
            f"{_rate(bucket['503'], bucket['total'])} |"
        )

    lines.extend(
        [
            "",
            "## Outcome classes",
            "",
            "| Outcome | Count |",
            "| :-- | --: |",
        ]
    )
    for outcome, count in Counter(str(r["outcome"]) for r in records).most_common():
        lines.append(f"| `{outcome}` | {count} |")
    lines.extend(
        [
            "",
            "## Files",
            "",
            "- Per-request log (UTC + Pacific, outcome, status, latency): "
            f"`{args.csv.relative_to(ROOT)}`",
            "",
            "## Limits",
            "",
            "- Ledger rows exist only for attempts that reached the client; a request rejected",
            "  before the provider (for example a pacing refusal) is not represented.",
            "- Hourly buckets with few requests are noisy; read them as counts, not as rates.",
            "",
        ]
    )
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(
        f"requests={total} failed={failures} 5xx={fives} 503={five_oh_three} "
        f"({_rate(five_oh_three, total)})"
    )
    print(f"report: {args.report}")
    print(f"csv: {args.csv}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
