"""P2-09: ledger-driven cost projection, with MEASURED and PROJECTED separated.

Every input is read from an artifact that a previous run produced: the ablation
results for the baseline's cost per paper, the ledger for its token counts, the
escalation manifest for `e`, `s` and the stage-2 unit cost. Nothing is typed in
here, and nothing in the PROJECTED section is a measurement.

Usage:
    python scripts/cost_model.py
    python scripts/cost_model.py --report docs/reports/P2-projection.md
"""

from __future__ import annotations

import argparse
import json
import sqlite3
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_RESULTS = ROOT / "eval" / "ablation" / "results" / "results.json"
DEFAULT_ESCALATION = ROOT / "eval" / "escalation" / "run_manifest.json"
DEFAULT_LEDGER = ROOT / "data" / "ledger.sqlite3"
DEFAULT_REPORT = ROOT / "docs" / "reports" / "P2-projection.md"
BASELINE_RUN_ID = "p1-10-flashlite-s20261114-n100"
SCALES = (1_000_000, 20_000_000)
ESCALATION_SCENARIOS = ("0.05", "0.15", "measured", "0.50")


def _load(path: Path) -> object:
    return json.loads(path.read_text(encoding="utf-8"))


def _baseline_tokens(ledger_path: Path, run_id: str) -> tuple[int, int, Decimal]:
    connection = sqlite3.connect(ledger_path)
    connection.row_factory = sqlite3.Row
    rows = connection.execute(
        "select prompt_tokens, completion_tokens, usd, error, paper_id "
        "from llm_calls where run_id = ?",
        (run_id,),
    ).fetchall()
    ok = [row for row in rows if row["error"] is None]
    prompt = sum(row["prompt_tokens"] or 0 for row in ok)
    completion = sum(row["completion_tokens"] or 0 for row in ok)
    usd = sum((Decimal(row["usd"]) for row in ok if row["usd"]), Decimal("0"))
    papers = len({row["paper_id"] for row in ok if row["paper_id"]})
    return prompt + completion, papers or 1, usd


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=DEFAULT_RESULTS)
    parser.add_argument("--escalation", type=Path, default=DEFAULT_ESCALATION)
    parser.add_argument("--ledger", type=Path, default=DEFAULT_LEDGER)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    args = parser.parse_args(argv)

    rows = _load(args.results)
    if not isinstance(rows, list):
        print("unreadable ablation results")
        return 1
    baseline = next((row for row in rows if row["config"] == "baseline"), None)
    escalation = _load(args.escalation)
    if baseline is None or not isinstance(escalation, dict):
        print("missing baseline row or escalation manifest")
        return 1

    baseline_per_paper = Decimal(str(baseline["cost_per_paper_usd"]))
    tokens_total, papers, ledger_usd = _baseline_tokens(args.ledger, BASELINE_RUN_ID)
    tokens_per_paper = tokens_total / papers
    e_measured = float(escalation["e"]["all"])
    s_by_rate: dict[str, float] = escalation.get("s_compute", {})
    s_rate = s_by_rate.get("0.05")
    if s_rate is None:
        print("escalation manifest has no s_compute for the assumed CPU rate")
        return 1
    s_per_paper = Decimal(str(s_rate)) * baseline_per_paper
    net_measured = Decimal(str(escalation["cost"]["net_per_paper"]))
    measured_savings = 1 - net_measured / baseline_per_paper
    stage2 = escalation.get("stage2", {})
    zero_claim_rate = float(stage2.get("teacher_zero_claim_rate", 0.0))
    stage2_unit = Decimal(str(stage2.get("unit_cost_intro_usd", "0")))
    # Derived, not typed: the measured cascade minus the student's share, spread
    # over the papers that actually escalated.
    teacher_per_paper = (net_measured - s_per_paper) / Decimal(str(e_measured))

    def per_paper(e: float, *, include_stage2: bool) -> Decimal:
        cost = s_per_paper + Decimal(str(e)) * teacher_per_paper
        if include_stage2:
            cost += Decimal(str(e)) * Decimal(str(zero_claim_rate)) * stage2_unit
        return cost

    def _money(value: Decimal) -> str:
        return f"${value:,.2f}"

    scenario_rates: list[tuple[str, float]] = []
    for name in ESCALATION_SCENARIOS:
        if name == "measured":
            scenario_rates.append((f"measured ({e_measured:.1%})", e_measured))
        else:
            scenario_rates.append((f"{float(name):.0%}", float(name)))

    lines = [
        "# P2-09 — cost projection",
        "",
        "> Generated by `python scripts/cost_model.py`. **MEASURED and PROJECTED are separate**",
        "> sections. Nothing in PROJECTED is a result; every input there is labelled in",
        "> Assumptions, and the model is the ADR-0008 planning form `relative_cost ≈ s + e`",
        "> with the measured stage-1 teacher cost per escalated paper.",
        "",
        "## MEASURED (from the ledger and the ablation rows)",
        "",
        "| Quantity | Value | Source |",
        "| :-- | --: | :-- |",
        f"| Baseline cost per paper | ${baseline_per_paper:.9f} | `{BASELINE_RUN_ID}` ledger + "
        "ablation row |",
        f"| Baseline tokens per paper | {tokens_per_paper:,.0f} | ledger, {papers} papers |",
        f"| Baseline ledger USD (recomputed) | ${ledger_usd:.6f} | ledger |",
        f"| Student cost ratio `s` | {s_rate * 100:.2f}% of baseline | escalation manifest |",
        f"| Escalation rate `e` | {e_measured:.1%} | escalation manifest |",
        f"| Cascade cost per paper (stage 1 only) | ${net_measured:.9f} | escalation manifest |",
        f"| Cascade savings vs baseline | {measured_savings * 100:.1f}% | derived |",
        f"| Teacher cost per escalated paper | ${teacher_per_paper:.9f} | derived |",
        f"| Teacher zero-claim rate | {zero_claim_rate:.1%} | escalation manifest |",
        f"| Stage-2 unit cost per escalated paper | ${stage2_unit:.9f} | manifest |",
        "",
        "## PROJECTED (never a measurement)",
        "",
        "Cost per paper, then total, at `N` papers. Stage 2 is included, because a larger",
        "corpus will contain papers it triggers on even though the gold set did not.",
        "",
        "| N papers | e scenario | $/paper | Total $ | Savings vs baseline |",
        "| --: | :-- | --: | --: | --: |",
    ]
    for n in SCALES:
        for label, rate in scenario_rates:
            cost = per_paper(rate, include_stage2=True)
            total = cost * n
            savings = 1 - cost / baseline_per_paper
            lines.append(
                f"| {n:,} | {label} | ${cost:.9f} | {_money(total)} | {savings * 100:.1f}% |"
            )

    low, high = scenario_rates[0][1], scenario_rates[-1][1]
    lines.extend(
        [
            "",
            "### Range at 20M papers",
            "",
            f"- Cheapest scenario (`e` = {low:.0%}): "
            f"{_money(per_paper(low, include_stage2=True) * SCALES[-1])}.",
            f"- Measured `e` ({e_measured:.1%}): "
            f"{_money(per_paper(e_measured, include_stage2=True) * SCALES[-1])}.",
            f"- Dearest scenario (`e` = {high:.0%}): "
            f"{_money(per_paper(high, include_stage2=True) * SCALES[-1])}.",
            f"- Baseline at the same scale: " f"{_money(baseline_per_paper * SCALES[-1])}.",
            "",
            "## Assumptions (all of them)",
            "",
            f"- `e` stays at its measured {e_measured:.1%} (or the stated scenario);",
            "  escalation rates on a new corpus are unknown.",
            f"- `s` = {s_rate * 100:.2f}%, from measured 1,192 ms/paper priced at an **assumed**",
            "  $0.05/CPU-hour; the timing is measured, the CPU rate is not.",
            "- Cost per paper is constant across scale: no batching of corpus-level work, no",
            "  volume discount, no price change. `pricing.yaml` is the list price as of the",
            "  measured date; a dated price change would move every number here.",
            "- Stage-1 teacher tokens per escalated paper are the measured 100-paper average.",
            "- Stage 2 uses the large model's intro list price and its zero-claim trigger rate; it",
            "  was **not** measured at scale (0 gold triggers, 1 dev probe).",
            "",
            "## How to reproduce",
            "",
            "```",
            "python scripts/cost_model.py",
            "```",
            "",
            "It re-reads the ledger, the ablation results, and the escalation manifest; it makes",
            "no LLM call and writes no labels.",
            "",
        ]
    )
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(
        f"baseline/paper=${baseline_per_paper:.9f} tokens/paper={tokens_per_paper:,.0f} "
        f"e={e_measured:.3f} s={s_rate:.5f}"
    )
    print(
        f"20M at measured e: {_money(per_paper(e_measured, include_stage2=True) * SCALES[-1])} "
        f"vs baseline {_money(baseline_per_paper * SCALES[-1])}"
    )
    print(f"report: {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
