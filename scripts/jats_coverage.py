"""Report JATS parse coverage over a directory of fixtures or cached papers.

Usage:
    python scripts/jats_coverage.py
    python scripts/jats_coverage.py --fixtures tests/fixtures/jats \
        --out docs/reports/P1-jats-coverage.md
    python scripts/jats_coverage.py --json

All numbers come from parsing the files in the directory; no network access.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from axion.parse.jats import ParsedPaper, corpus_coverage, paper_coverage, parse_jats_file


def _journal_map(fixtures: Path) -> dict[str, str]:
    manifest_path = fixtures / "manifest.json"
    if not manifest_path.exists():
        return {}
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    return {
        str(article["pmcid"]): str(article.get("journal") or "")
        for article in manifest.get("articles", [])
    }


def _load(fixtures: Path) -> list[ParsedPaper]:
    paths = sorted(fixtures.glob("*.xml.gz")) or sorted(fixtures.glob("*.xml"))
    return [parse_jats_file(path) for path in paths]


def render(paper_rows: list[ParsedPaper], journals: dict[str, str]) -> str:
    aggregate = corpus_coverage(paper_rows)
    lines = [
        "# JATS parse coverage",
        "",
        "Generated by `python scripts/jats_coverage.py --out docs/reports/P1-jats-coverage.md`.",
        "Fixtures are CC BY articles from Europe PMC; see `tests/fixtures/jats/manifest.json`.",
        "",
        "## Per paper",
        "",
        "| PMCID | Journal | Sections | Paragraphs | References | Refs with DOI | "
        "Bibr markers | Contexts | Resolved | Warnings |",
        "| :-- | :-- | --: | --: | --: | --: | --: | --: | --: | --: |",
    ]
    for paper in paper_rows:
        row = paper_coverage(paper)
        journal = journals.get(row.paper_id) or paper.journal or ""
        lines.append(
            f"| {row.paper_id} | {journal} | {row.sections} | {row.paragraphs} | "
            f"{row.references} | {row.references_with_doi} | {row.bibr_markers} | "
            f"{row.contexts} | {row.contexts_resolved} | {row.warnings} |"
        )

    lines += [
        "",
        "## Aggregate",
        "",
        f"- Papers: **{aggregate.papers}**",
        f"- Papers with at least one parsed citation context: "
        f"**{aggregate.papers_with_contexts} ({aggregate.percent_papers_with_contexts:.1f}%)**",
        f"- Papers with resolved contexts: **{aggregate.papers_with_resolved_contexts} "
        f"({aggregate.percent_papers_with_resolved_contexts:.1f}%)**",
        f"- Contexts: **{aggregate.contexts}**, resolved: **{aggregate.contexts_resolved} "
        f"({aggregate.percent_contexts_resolved:.1f}%)**",
        f"- References: **{aggregate.references}** "
        f"(DOI {aggregate.references_with_doi}, PMID {aggregate.references_with_pmid}, "
        f"title {aggregate.references_with_title}, year {aggregate.references_with_year})",
        f"- Sections: **{aggregate.sections}**; paragraphs: **{aggregate.paragraphs}**; "
        f"bibr markers: **{aggregate.bibr_markers}**",
        f"- Parser warnings: **{aggregate.warnings}**",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixtures", type=Path, default=Path("tests/fixtures/jats"))
    parser.add_argument("--out", type=Path, default=None, help="write Markdown here")
    parser.add_argument("--json", action="store_true", dest="as_json")
    args = parser.parse_args(argv)

    if not args.fixtures.exists():
        print(f"fixtures directory not found: {args.fixtures}", file=sys.stderr)
        return 1
    papers = _load(args.fixtures)
    if not papers:
        print(f"no JATS files found in {args.fixtures}", file=sys.stderr)
        return 1

    if args.as_json:
        output = json.dumps(corpus_coverage(papers).to_dict(), indent=2)
    else:
        output = render(papers, _journal_map(args.fixtures))
    print(output)

    if args.out is not None:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(output + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
